/** The shared finish card of a tab tour: its title and body are the only copy that differs. */
function finale(title: string, body: string): TourStep {
  return {
    id: "finale",
    kind: "finale",
    title,
    body,
    placement: "auto",
    shape: "rounded",
    padding: 0,
    primaryLabel: "Done",
  };
}

